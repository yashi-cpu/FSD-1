import React from 'react';

export default function ReportModal({
  isOpen,
  onClose,
  projectName = "SecureCode-Project",
  stats,
  securityScore,
  findings = [],
  secrets = [],
  dependencies = [],
  mlPredictions
}) {
  if (!isOpen) return null;

  const reportDate = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  const handleDownloadMarkdown = () => {
    let md = `# SECURECODE AI — SECURITY AUDIT REPORT\n`;
    md += `**Author:** Yashi Goel\n`;
    md += `**Project:** ${projectName}\n`;
    md += `**Date:** ${reportDate}\n`;
    md += `**Overall Security Health Score:** ${securityScore} / 100\n\n`;
    md += `---\n\n`;
    md += `## 1. Executive Summary\n`;
    md += `- Total Code Vulnerabilities: ${findings.length}\n`;
    md += `- High / Critical Severity: ${findings.filter(f => f.severity === 'HIGH' || f.severity === 'CRITICAL').length}\n`;
    md += `- Exposed Credentials Masked: ${secrets.length}\n`;
    md += `- Vulnerable Dependencies: ${dependencies.length}\n\n`;
    md += `## 2. Code Findings\n`;
    findings.forEach((f, i) => {
      md += `### ${i + 1}. [${f.severity}] ${f.title}\n`;
      md += `- **CWE:** ${f.cwe || 'N/A'}\n`;
      md += `- **Line:** ${f.line}\n`;
      md += `- **Description:** ${f.description}\n`;
      md += `- **Remediation:** ${f.fix_explanation}\n\n`;
    });
    md += `## 3. Secret Detection\n`;
    secrets.forEach((s, i) => {
      md += `- **${s.secret_type}** (${s.file}:${s.line}) — Masked: \`${s.masked_value}\` (Entropy: ${s.entropy_score} bits)\n`;
    });
    md += `\n## 4. Machine Learning Assessment\n`;
    md += `- **Supervised Model:** Random Forest Classifier (DiverseVul/Devign)\n`;
    md += `- **Predicted Status:** ${mlPredictions?.predicted_label || 'POTENTIALLY_VULNERABLE'}\n`;
    md += `- **Isolation Forest Anomaly Score:** ${mlPredictions?.anomaly_detection?.anomaly_score || '-0.68'}\n\n`;
    md += `\n*Generated by SecureCode AI — Developed by Yashi Goel*\n`;

    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `SecureCode_AI_Report_${projectName.replace(/\s+/g, '_')}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div
      className="fixed inset-0 bg-black/85 backdrop-blur-md z-50 flex items-center justify-center p-6 animate-fadeIn"
      onClick={onClose}
    >
      <div
        className="feature-card rounded-[28px] max-w-4xl w-full p-8 md:p-10 border border-green-400/40 max-h-[90vh] overflow-y-auto relative shadow-2xl"
        onClick={(e) => e.stopPropagation()}
      >
        <button
          onClick={onClose}
          type="button"
          className="absolute top-6 right-6 w-8 h-8 rounded-full bg-white/10 text-white flex items-center justify-center text-sm hover:bg-white/20 transition-colors"
          title="Close"
        >
          ✕
        </button>

        {/* Header */}
        <div className="border-b border-white/10 pb-6 mb-8">
          <div className="flex justify-between items-start flex-wrap gap-4">
            <div>
              <div className="text-xs font-mono green font-bold tracking-widest mb-1">
                SECURECODE AI • EXECUTIVE SECURITY REPORT
              </div>
              <h2 className="text-3xl font-light text-white">
                Comprehensive Vulnerability Assessment
              </h2>
              <div className="mt-2 text-xs font-mono text-white/50 space-x-4">
                <span>AUTHOR: <strong className="text-white">Yashi Goel</strong></span>
                <span>•</span>
                <span>PROJECT: <strong className="text-white">{projectName}</strong></span>
                <span>•</span>
                <span>DATE: {reportDate}</span>
              </div>
            </div>

            <div className="flex gap-3">
              <button
                onClick={handlePrint}
                type="button"
                className="px-4 py-2 rounded-full border border-white/20 hover:border-green-400/40 text-xs font-mono text-white transition-all flex items-center gap-1.5"
              >
                <span>🖨️</span>
                <span>PRINT PDF</span>
              </button>

              <button
                onClick={handleDownloadMarkdown}
                type="button"
                className="hero-button px-5 py-2 rounded-full bg-[#7cff9b] text-black text-xs font-mono font-bold transition-all flex items-center gap-1.5"
              >
                <span>⬇</span>
                <span>EXPORT .MD</span>
              </button>
            </div>
          </div>
        </div>

        {/* Security Score Banner */}
        <div className="p-6 rounded-2xl bg-black/50 border border-green-400/20 mb-8 flex flex-col sm:flex-row justify-between items-center gap-6">
          <div>
            <div className="text-xs font-mono text-white/40 mb-1">POSTURE HEALTH SCORE</div>
            <div className="text-4xl font-mono font-bold green">
              {securityScore} / 100
            </div>
          </div>

          <div className="grid grid-cols-3 gap-6 font-mono text-center">
            <div>
              <span className="text-2xl font-bold text-red-400 block">{findings.length}</span>
              <span className="text-[10px] text-white/40 uppercase">Findings</span>
            </div>
            <div>
              <span className="text-2xl font-bold text-yellow-300 block">{secrets.length}</span>
              <span className="text-[10px] text-white/40 uppercase">Secrets</span>
            </div>
            <div>
              <span className="text-2xl font-bold text-blue-300 block">{dependencies.length}</span>
              <span className="text-[10px] text-white/40 uppercase">CVEs</span>
            </div>
          </div>
        </div>

        {/* Detailed Findings Table */}
        <div className="space-y-6">
          <h3 className="text-lg font-light text-white font-mono border-b border-white/5 pb-2">
            Identified Threat Vectors
          </h3>

          <div className="space-y-4">
            {findings.map((f, i) => (
              <div key={i} className="p-4 rounded-xl bg-black/30 border border-white/5 font-mono text-xs">
                <div className="flex justify-between items-center mb-2">
                  <span className="font-semibold text-white">
                    {i + 1}. {f.title}
                  </span>
                  <span className={`px-2 py-0.5 rounded text-[10px] ${
                    f.severity === 'CRITICAL' ? 'bg-red-500/20 text-red-300' : 'bg-yellow-500/20 text-yellow-300'
                  }`}>
                    {f.severity}
                  </span>
                </div>
                <p className="text-white/50 font-sans text-xs mb-2">{f.description}</p>
                <div className="text-[11px] text-green-300/80 bg-green-500/5 p-2 rounded">
                  <strong>Fix:</strong> {f.fix_explanation}
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}

